<h3>ほうとう作り体験</h3>
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2615" src="assets/2-1024x683.png" alt="ほうとう作り体験" width="1024" height="683"></p>
<p>ほうとうとは、山梨県を中心によく食べられる郷土料理のことです。小麦粉を練りざっくりと切った太くて長い麺を、カボチャなど野菜と共に味噌仕立ての汁で煮込むのが特徴です。<br>

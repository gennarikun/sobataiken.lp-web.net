<dl class="veu_qaItem">
<dt>英語での対応は可能ですか？</dt>
<dd>はい。スタッフは英語での対応もできますので外国からのお客さまもお気軽にご利用ください。</dd>
</dl>
<dl class="veu_qaItem">
<dt>ネイルをしていても体験はできますか？</dt>

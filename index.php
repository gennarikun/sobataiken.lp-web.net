<dd>最寄駅は富士急行線河口湖駅で、徒歩12分ほどです。</dd>
</dl>
<dl class="veu_qaItem">
<dt>富士吉田河口湖店に駐車場はありますか？</dt>
<dd>はい。店舗前に無料駐車場がございますのでご利用下さい。</dd>
</dl>
<dl class="veu_qaItem">
<dt>富士吉田河口湖店には観光バスも駐車できますか</dt>

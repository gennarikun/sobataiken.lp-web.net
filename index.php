</dl>
<dl class="veu_qaItem">
<dt>クレジットカードは使えますか？</dt>
<dd>はい。クレジットカードもご利用いただけます。（VISA/Mastercard/AmericanExpressに限らせていただきます）</dd>
</dl>
<dl class="veu_qaItem">
<dt>富士吉田河口湖店は河口湖からはどのくらい時間がかかりますか？</dt>
<dd>お車でおよそ5分です。</dd>
</dl>
<dl class="veu_qaItem">

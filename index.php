<h3>特製激辛ほうとう</h3>
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2614" src="assets/1-1024x683.png" alt="ほうとう作り体験" width="1024" height="683"><br>
特製激辛ほうとうは、世の激辛好きのために考案した人気のメニューです。富士家オーナーが探し出した世界各地の激辛唐辛子を混ぜて作ったオリジナル味噌で味付けしたほうとうです。唐辛子を混ぜ込んだ真っ赤な麺は写真映えもします。ぜひお試しください。</p>
<h3>吉田のうどん作り体験</h3>
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2618" src="assets/5-1024x683.png" alt="吉田のうどん作り体験" width="1024" height="683"><br>
吉田のうどんとは、山梨県富士吉田市や河口湖近辺でよく食べられる郷土料理のうどんのことです。</p>
<p>河口湖は富士山の裾野にあり年間平均気温１１℃と大変寒く、稲作に不適合な地域だったため大麦・小麦・粟などが主食でした。今でこそ名物になっていますが、元々は富士吉田や河口湖の庶民的な家庭料理だったそうです。<br>
<a class="btn-lg btn btn-block btn-primary" href="https://houtoutaiken.lp-web.net/2019/10/29/about-yoshidanoudon/">吉田のうどんを詳しく知る</a></p>

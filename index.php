<h2 style="text-align: center;">体験の流れ</h2>
<div class="co">
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2661" src="assets/DSC04855-1024x683.jpg" alt="富士家体験教室" width="1024" height="683"></p>
<h4>1. 会場に到着</h4>
<p>体験開始時間の10分前にはお越し下さい。到着次第、店内にお入り下さい。</p>
</div>
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2662" src="assets/DSC05561-1-1024x683.jpg" alt="富士家体験教室" width="1024" height="683"></p>
<h4>2. 調理とそばの説明</h4>
<p>そば作り体験を始める前に当店の紹介ビデオをご視聴いただき、忍野八海そばについてのお話をさせていただきます。</p>
</div>
</div>
<div class="co">
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2663" src="assets/C0057T01-e1649639024361-1024x682.jpg" alt="蕎麦打ち体験" width="1024" height="682"></p>
<div class="caption">
<h4>3. 混ぜ</h4>
<p>当店では「そば粉１：つなぎ１」で蕎麦を作ります。そば粉150gを計った後、水を入れて素早くかき混ぜ、小さいダマをたくさん作ります。混ぜ続けると生地の色が濃くなってきます。水分が全体に行き渡ってきたら生地を一つにまとめていきます。</p>
</div>
</div>
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2655" src="assets/DSC05871-1024x683.jpg" alt="蕎麦打ち体験" width="1024" height="683"></p>
<div class="caption">
<h4>4. 捏ね</h4>
<p>生地を捏ねる際は、手のお腹を使って体重を掛けながら一つにまとめます。生地の表面に白い粉が残っている状態ですと、捏ねが不十分です。生地の表面全体がクリーミーになるまで力強く捏ねていきます。特にお子様ですと力が足りないこともあるので大人の方と協力しながら進めましょう。</p>
</div>
</div>
</div>
<div class="co">
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2656" src="assets/DSC05931-1024x683.jpg" alt="蕎麦打ち体験" width="1024" height="683"></p>
<div class="caption">
<h4>5. 延ばし</h4>
<p>生地が完成したら生地の表面に打ち粉をふりかけます。表面が白くなったら麺棒を使って生地を薄く伸ばしていきます。生地の形は正方形をイメージして延ばしていきましょう。どこから切っても麺の長さが均等になるよう、出来る限り正方形の形で延ばしていきます。</p>
</div>
</div>
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2657" src="assets/DSC05958-1024x683.jpg" alt="蕎麦打ち体験" width="1024" height="683"></p>
<div class="caption">
<h4>6. 切り</h4>
<p>生地を薄く延ばせたら、包丁の幅に収まるように生地を畳みます。畳み終えたら、こま板と包丁を使って切っていきます。一番難しい工程です。細く切るのは大変ですが、慣れてきたらテンポを上げて、出来たら10分以内に終わるように頑張りましょう。</p>
</div>
</div>
</div>
<div class="co">
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2658" src="assets/DSC06015-1024x683.jpg" alt="蕎麦打ち体験" width="1024" height="683"></p>
<div class="caption">
<h4>7. 記念撮影</h4>
<p>蕎麦の麺が完成したら、蕎麦と一緒に写真をお撮りします。記念撮影用の文字入り板もございますのでご希望の方はご利用下さい。お水と氷はセルフサービスになりますので必要な方はカウンターにあるドリンクコーナーからお取りください。</p>
</div>
</div>
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2659" src="assets/DSC06018-1024x683.jpg" alt="蕎麦打ち体験" width="1024" height="683"></p>
<div class="caption">
<h4>8. 茹で</h4>
<p>2分～3分ほど茹でます。つゆ・ネギ・海苔・ワサビはまとめてご提供しますのでお客様で取り分けて頂きますようお願いします。つゆは割っていないものと薄める用のお水をご提供しますので調整の方お願いいたします。</p>
</div>
</div>
</div>
<div class="co">
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2660" src="assets/DSC06025-1024x683.jpg" alt="蕎麦打ち他体験" width="1024" height="683"></p>
<div class="caption">
<h4>9. お取り分け</h4>
<p>手打ちそばの完成です。お蕎麦は大きめのざるに乗せてお席にお持ちいたします。お一人様ずつせいろをお渡ししますので、菜箸・トング等で取り分けて頂きますようお願いいたします。手打ち体験ならではの麺の違いをお楽しみください。麺とお客様のお写真も撮らせて頂きますのでお気軽にスタッフまでお申し付けください。</p>
</div>
</div>
<div class="boxbox">
<p><img loading="lazy" decoding="async" class="aligncenter size-large wp-image-2664" src="assets/DSC05723-1024x683.jpg" alt="すりだね販売" width="1024" height="683"></p>
<div class="caption">
<h4>10. 当店おすすめのすりだね</h4>
<p>すりだねとは、富士吉田市にある吉田のうどん屋に必ず置いてある名物の辛味調味料のことです。お蕎麦にはワサビもお付けしますが、すりだねも相性が良いので、是非お試しください。富士家のすりだねはオリジナルで60種類ご用意しております。辛さが苦手な方でも食べられるように辛さ控えめのものもございますのでお気軽にどうぞ。</p>
</div>
